/**
 * Builds a plain static copy of the website for ordinary web hosting (cPanel / Apache / Nginx / FTP).
 *
 *   npm run build:static
 *
 * Output: ./static-site   (upload the CONTENTS of this folder to your web host's public_html)
 *
 * Static hosting has no server, so the Next.js server-only parts are left out of this build:
 *   - /admin and /api routes (temporarily moved aside while building, then restored)
 *   - next.config redirects (re-created as .htaccess rules instead)
 * The contact form and PayPal checkout still work: they save to Convex directly from the browser.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDir = path.join(root, "src", "app");
const stashDir = path.join(root, ".static-stash");
const buildDir = path.join(root, "dist-static");
const outDir = path.join(root, "static-site");
const SERVER_ONLY = ["api", "admin"];

function stash() {
  fs.mkdirSync(stashDir, { recursive: true });
  for (const name of SERVER_ONLY) {
    const from = path.join(appDir, name);
    const to = path.join(stashDir, name);
    if (fs.existsSync(from)) fs.renameSync(from, to);
  }
}

function restore() {
  for (const name of SERVER_ONLY) {
    const from = path.join(stashDir, name);
    const to = path.join(appDir, name);
    if (fs.existsSync(from) && !fs.existsSync(to)) fs.renameSync(from, to);
  }
  if (fs.existsSync(stashDir) && fs.readdirSync(stashDir).length === 0) {
    fs.rmdirSync(stashDir);
  }
}

// Recover from a previously interrupted build before doing anything else
restore();

let restored = false;
const safeRestore = () => {
  if (!restored) {
    restored = true;
    restore();
  }
};
process.on("SIGINT", () => {
  safeRestore();
  process.exit(130);
});
process.on("exit", safeRestore);

let status = 1;
try {
  fs.rmSync(path.join(root, ".next"), { recursive: true, force: true });
  fs.rmSync(buildDir, { recursive: true, force: true });
  fs.rmSync(outDir, { recursive: true, force: true });
  stash();

  const nextBin = path.join(root, "node_modules", "next", "dist", "bin", "next");
  const result = spawnSync(process.execPath, [nextBin, "build"], {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, NEXT_PUBLIC_STATIC_EXPORT: "1" },
  });
  status = result.status ?? 1;
} finally {
  safeRestore();
}

if (status !== 0) {
  console.error("\nStatic build failed.");
  process.exit(status);
}

// Locate the exported site (distDir for static export is `dist-static`; `out` as a fallback)
const candidates = [buildDir, path.join(root, "out")];
const exported = candidates.find((d) => fs.existsSync(path.join(d, "index.html")));
if (!exported) {
  console.error("Could not find exported index.html in dist-static/ or out/.");
  process.exit(1);
}

fs.cpSync(exported, outDir, { recursive: true });
// Remove Next.js build internals if present; only the public site files are needed
for (const junk of ["cache", "types", "diagnostics", "server", "trace", "trace-build", "build-manifest.json", "package.json"]) {
  fs.rmSync(path.join(outDir, junk), { recursive: true, force: true });
}

// ── .htaccess (Apache): legacy Squarespace URL redirects + friendly 404 ──
const poems = JSON.parse(fs.readFileSync(path.join(root, "src", "data", "poems.json"), "utf-8"));
const legacy = JSON.parse(
  fs.readFileSync(path.join(root, "src", "data", "legacy-redirects.json"), "utf-8")
);
const rules = [
  ...legacy.map((r) => ({ from: r.source, to: r.destination })),
  ...poems.map((p) => ({ from: `/${p.slug}`, to: `/poems/${p.slug}` })),
];
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const htaccess = [
  "# Generated by scripts/build-static.mjs — upload together with the rest of the site",
  "Options -MultiViews",
  "DirectoryIndex index.html",
  "ErrorDocument 404 /404.html",
  "",
  "<IfModule mod_rewrite.c>",
  "  RewriteEngine On",
  "  # Old Squarespace URLs -> new pages (permanent)",
  ...rules.map(
    (r) => `  RewriteRule ^${esc(r.from.replace(/^\//, ""))}/?$ ${r.to === "/" ? "/" : r.to + "/"} [R=301,L]`
  ),
  "</IfModule>",
  "",
].join("\n");
fs.writeFileSync(path.join(outDir, ".htaccess"), htaccess, "utf-8");

// Don't leave the intermediate build folder around
fs.rmSync(buildDir, { recursive: true, force: true });

let files = 0;
let bytes = 0;
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else {
      files++;
      bytes += fs.statSync(p).size;
    }
  }
})(outDir);

console.log(`\n✔ Static site ready: ${outDir}`);
console.log(`  ${files} files, ${(bytes / 1024 / 1024).toFixed(1)} MB`);
console.log("  Upload the CONTENTS of that folder to your web host's public_html (include the hidden .htaccess).");
